"""Small shared library for the code accompanying the paper
"An extremal even unimodular lattice in dimension 112".

論文「112 次元の極値偶ユニモジュラー格子」に付けるコードの、共有の小さなライブラリ。

Modules / モジュール:
  data    read the four input files and check their SHA-256 hashes
          4 つの入力ファイルを読み、SHA-256 を照合する
  exact   exactness guards for floating-point products, exact rational/integer linear algebra
          浮動小数点の行列積が厳密であることの確認、有理数・整数の厳密な線形代数
  group   enumerate the 12,180 elements of SL_2(29)/{+-1} from the two generators
          2 つの生成元から SL_2(29)/{±1} の 12,180 元を列挙する
  mod2    classes modulo 2L as 56-bit integers, and their canonical forms
          2L を法とする類（56 ビットの整数）と、その標準形
  shells  inner products with all minimal vectors of L
          L のすべての最小ベクトルとの内積
  certs   reading and writing certificate files (.npz without pickle)
          検証用データ（pickle を使わない .npz）の読み書き
  enumerate  all short vectors by the interval-arithmetic enumerator verify/enum_interval.c
          区間演算の列挙器 verify/enum_interval.c による短いベクトルの列挙
  report  [ok]/[FAIL] lines and the JSON file out/<step>.json
          [ok]/[FAIL] の表示と JSON ファイル out/<step>.json

Only numpy and the Python standard library are used.
numpy と Python の標準ライブラリだけを使う。

Conventions (as in the paper, §2.1) / 約束（論文 §2.1 と同じ）:
  * vectors are integer ROW vectors; a matrix M acts by x -> x M;
    ベクトルは整数の行ベクトル。行列 M は x -> x M で作用する。
  * <x, y> = x G y^T; "norm" means <x, x> (not its square root);
    <x, y> = x G y^T。「ノルム」は <x, x>（平方根ではない）。
  * g is an isometry of L iff g G g^T = G.
    g が L の等長変換 ⟺ g G g^T = G。
  * S is the group generated by g1, g2 (an image of SL_2(29)); S* = S C with the centralizer C.
    S は g1, g2 が生成する群（SL_2(29) の像）。S* = S C（C は中心化群）。

Guards / 保証の検査:
  Every condition on which a result depends (exactness of floating-point products, absence of
  overflow, completeness of an expansion or enumeration, ...) is checked by `require`, which
  raises `CheckError`. `assert` is not used for this, because `python -O` (or PYTHONOPTIMIZE)
  removes assert statements. In addition, importing this package under `-O` is refused, so a run
  in optimized mode stops at once instead of silently skipping checks elsewhere.
  CheckError derives from RuntimeError, not AssertionError, so that code catching
  AssertionError (for example around a test assertion) cannot swallow a failed guard.
  結果が依存する条件（浮動小数点の積が厳密なこと、オーバーフローしないこと、展開や列挙が完全なことなど）は、
  `require` で確かめる。偽なら `CheckError` を送出する。`python -O`（または PYTHONOPTIMIZE）は assert 文を取り除くので、
  これには assert を使わない。さらに、-O の下でこのパッケージを読み込むことを拒否する。最適化モードでの実行は、
  どこかの検査を黙って飛ばす代わりに、すぐに止まる。
  CheckError は AssertionError ではなく RuntimeError から派生させる。AssertionError を捕まえるコード
  （例えば試験の assert の周り）が、失敗した検査を握りつぶすことがないようにするためである。
"""

if not __debug__:
    raise SystemExit("refusing to run under python -O / PYTHONOPTIMIZE: the checks must not be optimized away; "
                     "run without -O (the shell scripts use python -I, which also ignores PYTHONOPTIMIZE)\n"
                     "python -O / PYTHONOPTIMIZE の下では実行しない（検査が取り除かれてはならない）。-O を付けずに実行する"
                     "（シェルスクリプトは python -I で呼ぶので PYTHONOPTIMIZE も無視される）")


class CheckError(RuntimeError):
    """A guard of the verification failed (see `require`). / 検算の保証の検査が失敗した（`require` を参照）。"""


def require(cond, msg):
    """Raise CheckError(msg) unless `cond` is true. Unlike `assert`, this is never removed by -O.
    `cond` が真でなければ CheckError(msg) を送出する。`assert` と違って -O でも取り除かれない。"""
    if not cond:
        raise CheckError(msg)
