"""S4. Route S (sampling; NOT a proof): re-check randomly chosen certificates with
plain int64 arithmetic, without the float32 products and the shared library of verify/
(supplement §S3.2, Table S7). The complete checks are verify/v5 and verify/v7.
S4. 経路 S（抜き取り。証明では**ない**）: 無作為に選んだ certificate を、verify/ の float32 の積や共有ライブラリを使わず、素朴な int64 の演算で
検算する（補遺 §S3.2、表 S7）。全数の検算は verify/v5 と verify/v7。

For each sampled certificate w0 (odd: of r_j tau + 2L; even: of x_i u_k tau + 2L):
  (a) w0 minus the class representative has even coordinates; (b) its norm is 14 or 18 (odd) or
  12, 16, 20 (even); (c) max |<w0, u>| <= 6 over all minimal vectors u = r s (s in S/{+-1}).
The group is rebuilt here from g1, g2 by breadth-first search.
標本の各 certificate w0 について (a) 類の代表との差の座標が偶数、(b) ノルムが 14, 18（奇）または 12, 16, 20（偶）、
(c) すべての最小ベクトル u = r s との |<w0, u>| の最大が 6 以下。群はここで g1, g2 から幅優先で作り直す。

Why it is not a proof: if a fraction p of the entries were wrong, k samples would detect it only
with probability 1 - (1 - p)^k.
証明にならない理由: 誤りが割合 p あっても、k 個の標本で見つかる確率は 1 - (1 - p)^k にすぎない。

The input files are checked against data/SHA256SUMS and certificates/SHA256SUMS with hashlib (still without
the shared library). The result is written to out/s4_sample_check.json; the exit code is 1 if a hash differs
or a sampled certificate fails.
入力ファイルは hashlib で data/SHA256SUMS と certificates/SHA256SUMS に照合する（共有ライブラリは使わない）。結果は
out/s4_sample_check.json に書き、ハッシュが違うか標本の certificate が一つでも不合格なら終了コード 1 で終わる。

Only numpy. Run time: about 10 minutes for k = 200 + 200. Memory: about 1 GB.
numpy のみ。実行時間: k = 200 + 200 で約 10 分。メモリ: 約 1 GB。
Run / 実行:  python3 -I code/supplementary/sample_check.py [--k 200] [--seed 1] [--out DIR]
"""
import argparse
import hashlib
import json
import os
import platform
import sys
import time

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def ints(path):
    return np.array([int(t) for line in open(path) if not line.startswith("#") for t in line.split()], dtype=np.int64)


def npz(name, key):
    with np.load(os.path.join(ROOT, "certificates", name), allow_pickle=False) as z:
        return z[key]


def check_hashes(files):
    """SHA-256 of each (directory, name) against directory/SHA256SUMS; returns the list of mismatches.
    各ファイルの SHA-256 を同じディレクトリの SHA256SUMS と照合し、合わないものの一覧を返す。"""
    bad = []
    for d, name in files:
        sums = {}
        for line in open(os.path.join(ROOT, d, "SHA256SUMS")):
            if line.strip():
                h, f = line.split()
                sums[f.lstrip("*")] = h
        h = hashlib.sha256()
        with open(os.path.join(ROOT, d, name), "rb") as f:
            for blk in iter(lambda: f.read(1 << 24), b""):
                h.update(blk)
        if sums.get(name) != h.hexdigest():
            bad.append(f"{d}/{name}")
    return bad


def group_mod_sign(gens, G, order):
    """All elements of <gens> by breadth-first search (int16 storage, int64 products), one of each +-pair.
    <gens> の全元を幅優先で（int16 で保存、int64 で積）。±の片方ずつ。"""
    n = G.shape[0]
    I16 = np.eye(n, dtype=np.int16)
    seen = {I16.tobytes(): I16}
    frontier = [I16]
    while frontier:
        nxt = []
        for A in frontier:
            for g in gens:
                B = A.astype(np.int64) @ g
                if np.abs(B).max() >= 2 ** 15:
                    sys.exit("group element with an entry >= 2^15: int16 storage would not be exact")
                B16 = B.astype(np.int16)
                k = B16.tobytes()
                if k not in seen:
                    seen[k] = B16
                    nxt.append(B16)
        frontier = nxt
    els = list(seen.values())
    if len(els) != order:
        sys.exit(f"[FAIL] the group generated by g1, g2 has {len(els)} elements, not {order}")
    half = {}
    for g in els:
        half.setdefault(min(g.tobytes(), (-g).tobytes()), g)
    return np.stack(list(half.values())).astype(np.int64)


def main():
    ap = argparse.ArgumentParser(description="S4: sampling check (not a proof)")
    ap.add_argument("--k", type=int, default=200)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", default=os.path.join(ROOT, "out"))
    a = ap.parse_args()
    t0 = time.time()
    rng = np.random.default_rng(a.seed)
    n = 56
    files = [("data", f) for f in ("L56_gram.txt", "sl2_29_generators.txt", "tau.txt")] + \
            [("certificates", f) for f in ("min_reps.npz", "odd_bounding.npz", "norm8_reps.npz", "centralizer.npz", "even_bounding.npz")]
    mismatch = check_hashes(files)
    if mismatch:
        sys.exit(f"[FAIL] SHA-256 differs from SHA256SUMS: {mismatch}")
    print(f"SHA-256 of {len(files)} input files agree with SHA256SUMS", flush=True)
    G = ints(os.path.join(ROOT, "data", "L56_gram.txt")).reshape(n, n)
    g1, g2 = ints(os.path.join(ROOT, "data", "sl2_29_generators.txt")).reshape(2, n, n)
    tau = ints(os.path.join(ROOT, "data", "tau.txt")).reshape(n, n)
    E = group_mod_sign([g1, g2], G, 24360)
    print(f"group rebuilt from g1, g2: {len(E)} elements modulo sign", flush=True)
    R6 = npz("min_reps.npz", "reps").astype(np.int64)
    R6T = R6.T.copy()

    def max_ip(w):
        t = E @ (G @ w)                      # (12180, 56): t[s] = s G w^T
        return int(np.abs(t @ R6T).max())    # <r s, w> = r . (s G w^T), all in int64

    W6 = npz("odd_bounding.npz", "w0").astype(np.int64)
    bad = 0
    k_odd, k_even = min(a.k, len(W6)), None
    for j in rng.choice(len(W6), size=k_odd, replace=False):
        w0 = W6[j]
        bad += not (((w0 - R6[j] @ tau) % 2 == 0).all() and int(w0 @ G @ w0) in (14, 18) and max_ip(w0) <= 6)
    print(f"odd-class certificates: {min(a.k, len(W6))} sampled, {bad} failed", flush=True)
    bad_odd = bad

    X = npz("norm8_reps.npz", "reps").astype(np.int64)
    U = npz("centralizer.npz", "units").astype(np.int64)
    W8 = npz("even_bounding.npz", "w0")
    bad, hist = 0, {}
    k_even = min(a.k, len(W8))
    for p in rng.choice(len(W8), size=k_even, replace=False):
        w0 = W8[p].astype(np.int64)
        i, k = divmod(int(p), 6)
        cls = ((w0 - X[i] @ U[k] @ tau) % 2 == 0).all()
        N, m = int(w0 @ G @ w0), max_ip(w0)
        hist[f"{N},{m}"] = hist.get(f"{N},{m}", 0) + 1
        bad += not (cls and N in (12, 16, 20) and m <= 6)
    print(f"even-class certificates: {k_even} sampled, {bad} failed; (norm, max |ip|) -> count {hist}", flush=True)
    print("detection probability for a fraction p of wrong entries: " +
          ", ".join(f"p = {p:g}: {1 - (1 - p) ** k_even:.3f}" for p in (1e-2, 1e-3, 1e-4, 10 / 1527984)))
    passed = bad == 0 and bad_odd == 0
    result = {"step": "s4_sample_check", "passed": passed, "seed": a.seed,
              "odd": {"sampled": k_odd, "failed": bad_odd}, "even": {"sampled": k_even, "failed": bad, "norm,max_ip": hist},
              "seconds": round(time.time() - t0, 1), "finished": time.strftime("%Y-%m-%d %H:%M:%S %z"),
              "python": platform.python_version(), "numpy": np.__version__, "platform": platform.platform()}
    os.makedirs(a.out, exist_ok=True)
    path = os.path.join(a.out, "s4_sample_check.json")
    with open(path + ".tmp", "w") as f:
        json.dump(result, f, indent=1)
        f.write("\n")
    os.replace(path + ".tmp", path)
    print(f"{'PASSED' if passed else 'FAILED'}: s4_sample_check -> {path}", flush=True)
    sys.exit(0 if passed else 1)


if __name__ == "__main__":
    main()
